//! The `livekit.yaml` that hatavoice-server writes before starting its LiveKit child.

use std::net::IpAddr;

use hv_host::{HostConfig, Secrets};

/// The codecs a call may use. Chromium encodes LiveKit's H.264 (Constrained Baseline 42e01f) on the processor, but
/// Main 4d001f on the video card: LiveKit offers its strict Main variant only for this exact `fmtp_line`, and the
/// plain entry must stay too, as LiveKit checks a published track's codec by mime alone and would fall back to VP8.
/// The client puts Main first in its offer (`voice/h264Main.ts`); a PC without a hardware Main encoder gets 42e01f.
const ENABLED_CODECS: &str = "room:\n\
     \x20 enabled_codecs:\n\
     \x20   - mime: audio/opus\n\
     \x20   - mime: audio/red\n\
     \x20   - mime: video/vp8\n\
     \x20   - mime: video/h264\n\
     \x20   - mime: video/h264\n\
     \x20     fmtp_line: level-asymmetry-allowed=1;packetization-mode=1;profile-level-id=4d001f\n\
     \x20   - mime: video/vp9\n\
     \x20   - mime: video/av1\n\
     \x20   - mime: video/rtx\n";

/// Renders LiveKit's config. With a known public IP, LiveKit advertises it alongside the LAN
/// addresses, so friends from the internet and from the same flat can both connect.
///
/// Signaling (HTTP/WebSocket) listens on loopback only: friends reach it through our TLS port and `/rtc`
/// proxy, which turns away kicked and banned passes. `bind_addresses` does not touch the media ports.
pub fn render(config: &HostConfig, secrets: &Secrets, public_ip: Option<IpAddr>) -> String {
    let mut yaml = format!(
        "# Generated by hatavoice-server on every start; edits are overwritten.\n\
         port: {livekit_port}\n\
         bind_addresses:\n\
         \x20 - 127.0.0.1\n\
         rtc:\n\
         \x20 tcp_port: {tcp}\n\
         \x20 udp_port: {udp}\n\
         \x20 use_external_ip: false\n",
        livekit_port = config.livekit_port,
        tcp = config.rtc_tcp_port,
        udp = config.rtc_udp_port,
    );
    if let Some(ip) = public_ip {
        yaml.push_str(&format!("  node_ip: {ip}\n  advertise_internal_ip: true\n"));
    }
    yaml.push_str(ENABLED_CODECS);
    yaml.push_str(&format!(
        "keys:\n\
         \x20 {key}: {secret}\n\
         logging:\n\
         \x20 level: warn\n",
        key = secrets.livekit_key,
        secret = secrets.livekit_secret,
    ));
    yaml
}

#[cfg(test)]
mod tests {
    use super::*;

    fn secrets() -> Secrets {
        Secrets { livekit_key: "hvkey01".into(), livekit_secret: "s".repeat(64) }
    }

    #[test]
    fn uses_configured_ports_and_generated_keys() {
        let config = HostConfig { rtc_tcp_port: 9001, rtc_udp_port: 9002, livekit_port: 9003, ..Default::default() };
        let yaml = render(&config, &secrets(), None);
        assert!(yaml.contains("port: 9003\n"));
        assert!(yaml.contains("  tcp_port: 9001\n"));
        assert!(yaml.contains("  udp_port: 9002\n"));
        assert!(yaml.contains(&format!("  hvkey01: {}\n", "s".repeat(64))));
        assert!(yaml.contains("  level: warn\n"));
        assert!(!yaml.contains("devkey"));
    }

    #[test]
    fn signaling_listens_on_loopback_only() {
        for public_ip in [None, Some("203.0.113.7".parse().unwrap())] {
            let yaml = render(&HostConfig::default(), &secrets(), public_ip);
            // Top level, so it moves the HTTP/WebSocket signaling listener and leaves the media ports alone.
            assert!(yaml.contains("\nbind_addresses:\n  - 127.0.0.1\n"), "{yaml}");
        }
    }

    #[test]
    fn never_asks_a_third_party_stun_server_for_the_public_ip() {
        let yaml = render(&HostConfig::default(), &secrets(), None);
        assert!(yaml.contains("  use_external_ip: false\n"));
        assert!(!yaml.contains("node_ip"));
    }

    #[test]
    fn offers_h264_main_beside_the_plain_h264_entry() {
        let yaml = render(&HostConfig::default(), &secrets(), None);
        let codecs = yaml.split("\nroom:\n  enabled_codecs:\n").nth(1).expect(&yaml);
        let mimes: Vec<&str> = codecs.lines().filter_map(|l| l.strip_prefix("    - mime: ")).collect();
        assert_eq!(
            mimes,
            ["audio/opus", "audio/red", "video/vp8", "video/h264", "video/h264", "video/vp9", "video/av1", "video/rtx"]
        );
        // LiveKit enables its strict Main variant only for this exact line; the plain entry keeps H.264 publishable.
        assert!(codecs.contains(
            "    - mime: video/h264\n      fmtp_line: level-asymmetry-allowed=1;packetization-mode=1;profile-level-id=4d001f\n"
        ));
        assert_eq!(codecs.matches("fmtp_line").count(), 1);
    }

    #[test]
    fn known_public_ip_is_advertised_together_with_lan_addresses() {
        let ip: IpAddr = "203.0.113.7".parse().unwrap();
        let yaml = render(&HostConfig::default(), &secrets(), Some(ip));
        assert!(yaml.contains("  node_ip: 203.0.113.7\n"));
        assert!(yaml.contains("  advertise_internal_ip: true\n"));
    }
}
